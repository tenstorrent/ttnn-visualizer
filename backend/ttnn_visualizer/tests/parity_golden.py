"""What the agent's parity goldens share: how each is written, held and read by its spec.

A test module that builds a `Golden` writes a golden of a port's answers, and a spec in
`tests/` holds the app's functions to it. Each such module must be listed in
`agent:parity-golden` in `package.json`, or it is never regenerated;
`test_parity_golden.py` enforces that.

    pnpm run agent:parity-golden    <- regenerates every golden
"""

import json
import os
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Mapping

from ttnn_visualizer.utils import str_to_bool

_REPOSITORY_ROOT = Path(__file__).resolve().parents[3]
_UPDATE = "UPDATE_AGENT_PARITY_GOLDEN"


def round_trip(value: object) -> object:
    """A value as a golden holds it, after JSON."""
    return json.loads(json.dumps(value))


def report_rows(
    defaults: Mapping[str, object], *overrides: Mapping[str, object]
) -> List[Dict[str, object]]:
    """Report rows as the generator writes them: cells are text, ids CSV positions from 2."""
    return [
        {"id": str(index + 2), **defaults, **fields}
        for index, fields in enumerate(overrides)
    ]


@dataclass(frozen=True)
class Golden:
    """`tests/data/<name>.json`, written by `generator`, and `tests/<name>.spec.ts`.

    `generator` is the writing module's `__file__`, which the golden's `_comment` names.
    """

    name: str
    generator: str

    @property
    def path(self) -> Path:
        return _REPOSITORY_ROOT / "tests" / "data" / f"{self.name}.json"

    @property
    def spec(self) -> Path:
        return _REPOSITORY_ROOT / "tests" / f"{self.name}.spec.ts"

    @property
    def comment(self) -> str:
        generator = Path(self.generator).resolve().relative_to(_REPOSITORY_ROOT)
        return (
            f"Generated by {generator.as_posix()}. Do not edit by hand; "
            "run pnpm run agent:parity-golden."
        )

    def check(self, generated: Mapping[str, object]) -> None:
        """Write the golden when asked to, then require the committed one to match."""
        held = round_trip({"_comment": self.comment, **generated})
        text = json.dumps(held, separators=(",", ":")) + "\n"
        if str_to_bool(os.environ.get(_UPDATE, "false")):
            self.path.write_text(text)

        assert self.path.exists(), (
            f"Golden file missing: {self.path}. Generate it with "
            "pnpm run agent:parity-golden."
        )
        changed = (
            "A port's answers changed. If the app's functions changed too, regenerate "
            f"with pnpm run agent:parity-golden and check tests/{self.spec.name} passes."
        )
        committed = self.path.read_text()
        assert held == json.loads(committed), changed
        # As text too: a negative zero equals zero, and the app's spec tells them apart.
        assert text == committed, changed

    def check_spec_reads_it(self) -> None:
        """The spec reads this golden, and its header names the module that writes it."""
        spec = self.spec.read_text()
        assert re.search(
            rf"from '\./data/{re.escape(self.path.name)}'", spec
        ), f"{self.spec.name} does not read {self.path.name}"
        generator = Path(self.generator).name
        assert re.search(
            rf"\b{re.escape(generator)}\b", spec
        ), f"{self.spec.name} does not name {generator}, which writes its golden"
