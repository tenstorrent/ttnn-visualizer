"""`parity_golden.py`, and the rule that `agent:parity-golden` regenerates every golden.

A golden left out of the script is never regenerated, and its test then fails only as
"a port's answers changed".
"""

import json
import re
from pathlib import Path
from typing import List

from ttnn_visualizer.tests.parity_golden import Golden, report_rows

_TESTS = Path(__file__).resolve().parent
_REPOSITORY_ROOT = _TESTS.parents[2]
_BUILDS_A_GOLDEN = re.compile(r"\bGolden\(")


def _golden_modules() -> List[Path]:
    return sorted(
        path
        for path in _TESTS.glob("test_*.py")
        if path.name != Path(__file__).name
        and _BUILDS_A_GOLDEN.search(path.read_text())
    )


def _script() -> str:
    package = json.loads((_REPOSITORY_ROOT / "package.json").read_text())
    return package["scripts"]["agent:parity-golden"]


def _relative(path: Path) -> str:
    return path.relative_to(_REPOSITORY_ROOT).as_posix()


def test_some_module_builds_a_golden():
    assert _golden_modules()


def test_every_golden_module_is_regenerated_by_the_script():
    script = _script().split()
    missing = [
        _relative(path) for path in _golden_modules() if _relative(path) not in script
    ]

    assert not missing, f"Add to agent:parity-golden in package.json: {missing}"


def test_every_module_the_script_runs_builds_a_golden():
    listed = [word for word in _script().split() if word.endswith(".py")]

    assert sorted(listed) == [_relative(path) for path in _golden_modules()]


def test_every_golden_names_the_module_that_writes_it():
    for path in _golden_modules():
        assert re.search(
            r'\bGolden\("\w+", __file__\)', path.read_text()
        ), f"{path.name} must build its Golden with __file__"


def test_the_comment_names_the_generating_module():
    assert Golden("example", __file__).comment == (
        "Generated by backend/ttnn_visualizer/tests/test_parity_golden.py. "
        "Do not edit by hand; run pnpm run agent:parity-golden."
    )


def test_report_rows_number_ids_from_two():
    assert report_rows({"a": "x"}, {}, {"a": "y"}) == [
        {"id": "2", "a": "x"},
        {"id": "3", "a": "y"},
    ]
